    /** Обрати тему, доречну для місця і не з тих, що були нещодавно. */
    public static Topic pickTopic(String place, List<String> recentTopics, Random random) {
        List<Topic> fitting = TOPICS.stream().filter(t -> t.fitsPlace(place)).toList();
        List<Topic> fresh = fitting.stream()
                .filter(t -> !recentTopics.contains(t.key()))
                .toList();
        List<Topic> pool = fresh.isEmpty() ? fitting : fresh;
        return pool.get(random.nextInt(pool.size()));
    }

    /** Де гравець сьогодні (визначає сервер за прапорцями гри). */
    public static String placeOf(GameRun run, boolean isWeekend) {
        if (isWeekend) return "weekend";
        Object mode = run.getFlags().get("dayMode");
        String m = mode != null ? mode.toString() : "home";
        return List.of("university", "work", "home").contains(m) ? m : "home";
    }

