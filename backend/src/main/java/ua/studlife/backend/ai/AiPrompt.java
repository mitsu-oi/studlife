    // phases — у яку фазу дня тема доречна (null = будь-коли).
    public record Topic(String key, String hint, List<String> where, List<String> phases) {
        /** Короткий запис для тем без обмеження по часу доби. */
        public Topic(String key, String hint, List<String> where) {
            this(key, hint, where, null);
        }

        public boolean fitsPlace(String place) {
            return where == null || where.contains(place);
        }

        public boolean fitsPhase(String phase) {
            return phases == null || phases.contains(phase);
        }
    }

