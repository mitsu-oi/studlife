    public static String placeRule(String place) {
        return switch (place) {
            case "university" -> PLACE_RULES_UNIVERSITY;
            case "work" -> PLACE_RULES_WORK;
            case "weekend" -> PLACE_RULES_WEEKEND;
            default -> PLACE_RULES_HOME;
        };
    }

