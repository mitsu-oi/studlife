package ua.studlife.backend.config;

import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

import java.time.Instant;
import java.util.Map;

/**
 * «СЕРВЕР ЖИВИЙ?» — найпростіша адреса в усьому проєкті.
 *
 * НАВІЩО ВОНА ПОТРІБНА:
 *
 * 1. Щоб перевірити сервер, не заводячи акаунт. Відкрила з телефона
 *    /api/health — побачила «ok» — значить, сервер працює і справа не в ньому.
 *    Без такої адреси єдиний спосіб перевірки — спробувати залогінитись,
 *    а там уже сто причин, чому могло не вийти.
 *
 * 2. Щоб хостинг розумів, чи піднялась програма. Render стукає сюди після
 *    кожного оновлення: відповіли «ok» — деплой вдалий, мовчимо — щось лягло.
 *
 * 3. Щоб будити сервер. На безкоштовному тарифі він засинає після 15 хвилин
 *    тиші й потім прокидається майже хвилину. Гра може тихенько смикнути цю
 *    адресу ще на екрані входу — поки гравець вписує пароль, сервер уже встане.
 *
 * ⚠️ ТУТ НЕ МОЖНА ПИСАТИ НІЧОГО ЗАЙВОГО. Адреса відкрита всьому інтернету
 * без пароля. Версія програми, стан бази, назви бібліотек — усе це підказки
 * для того, хто шукатиме дірку. Тому тільки «живий» і котра година.
 */
@RestController
public class HealthController {

    @GetMapping("/api/health")
    public Map<String, Object> health() {
        return Map.of(
                "status", "ok",
                // час сервера — видно, чи це свіжа відповідь, чи браузер
                // показує стару, збережену в пам'яті
                "time", Instant.now().toString()
        );
    }
}
